"""Dota 2 with Large Scale Deep Reinforcement Learning -- OpenAI Five (Berner et al., OpenAI 2019).

  the system      PPO with GAE on a 4096-unit LSTM (one network copy per hero), self-play, ~1-3 million timesteps per
                  batch, asynchronous rollout workers and optimizer GPUs, 10 months, 770 +- 50 PFlops/s-days
  surgery         change the network / observations / actions WITHOUT restarting: build a new model that computes the
                  same function (Net2Net-style): new hidden units get random incoming weights and ZERO outgoing
                  weights; new observations get ZERO weights; the LSTM 2048 -> 4096 widening needed small random
                  weights instead (no exact separation in a recurrent layer)
  data quality    staleness (data generated by parameters N versions old) and sample reuse (each sample used k times)
                  slow learning sharply; larger batches speed it up, but sublinearly
  team spirit     r_i = (1 - tau) rho_i + tau mean(rho): low tau early (less gradient noise), annealed to tau = 1

This file implements surgery operations on a small MLP policy (exact and approximate), a PPO + GAE learner on the
vectorised CartPole from paper 095, the paper's data-quality ablations (batch size, staleness, sample reuse) at toy
scale, a 'surgery vs restart' run on an environment that gains new observations over time, and a team-spirit toy.
"""

